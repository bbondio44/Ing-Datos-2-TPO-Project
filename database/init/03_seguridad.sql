-- Endurecimiento mínimo de PostgreSQL. Las credenciales se suministran por entorno.
BEGIN;

REVOKE ALL ON SCHEMA tp_logistica FROM PUBLIC;
GRANT USAGE ON SCHEMA tp_logistica TO CURRENT_USER;

REVOKE ALL ON ALL TABLES IN SCHEMA tp_logistica FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA tp_logistica FROM PUBLIC;
REVOKE ALL ON ALL FUNCTIONS IN SCHEMA tp_logistica FROM PUBLIC;

GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA tp_logistica TO CURRENT_USER;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA tp_logistica TO CURRENT_USER;
GRANT EXECUTE ON ALL FUNCTIONS IN SCHEMA tp_logistica TO CURRENT_USER;

ALTER DEFAULT PRIVILEGES IN SCHEMA tp_logistica REVOKE ALL ON TABLES FROM PUBLIC;
ALTER DEFAULT PRIVILEGES IN SCHEMA tp_logistica REVOKE ALL ON SEQUENCES FROM PUBLIC;
ALTER DEFAULT PRIVILEGES IN SCHEMA tp_logistica REVOKE ALL ON FUNCTIONS FROM PUBLIC;

COMMIT;
